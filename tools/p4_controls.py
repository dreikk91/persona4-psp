#!/usr/bin/env python
"""List the port's runtime controls straight from port/: every file-scope p4_* variable defined with an initializer.

  python tools/p4_controls.py            # summary counts
  python tools/p4_controls.py --md FILE  # write the markdown table (docs/runtime_controls.md)

A variable without an initializer (counters, pointers, state) is not a control. Diagnostic controls are the ones named
*_check, *_census, *_trace, *_stats, p4_probe_*, p4_exp_*, or defined under #ifdef P4_HW_PROFILE.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEF = re.compile(r"^(?:volatile\s+)?(?:static\s+)?(int|unsigned(?: int)?|float|short|signed char|unsigned char)\s+(p4_\w+\s*=.*?);", re.M)
DIAG = re.compile(r"(_check|_census|_trace|_stats)$|^p4_(probe|exp)_")


def controls(port=ROOT / "port"):
    found = []
    for path in sorted(list(port.glob("*.c")) + list(port.glob("*.h"))):
        text = path.read_text(encoding="latin-1")
        prof = [(m.start(), m.group(1)) for m in re.finditer(r"^#\s*(ifdef P4_HW_PROFILE|if|ifdef|ifndef|else|endif)\b", text, re.M)]
        for m in DEF.finditer(text):
            line = text.count("\n", 0, m.start()) + 1
            depth = []  # per open #if: [is #ifdef P4_HW_PROFILE, in its first branch]
            for at, kind in prof:
                if at > m.start():
                    break
                if kind.startswith("if"):
                    depth.append([kind == "ifdef P4_HW_PROFILE", True])
                elif kind == "else" and depth:
                    depth[-1][1] = False
                elif kind == "endif" and depth:
                    depth.pop()
            inprof = any(p and first for p, first in depth)
            for part in re.split(r",\s*(?=p4_\w+\s*=)", m.group(2)):
                name, value = (x.strip() for x in part.split("=", 1))
                found.append(dict(name=name, value=value, type=m.group(1), file=path.name, line=line,
                                  diag=bool(DIAG.search(name)) or inprof))
    return found


def markdown(items):
    out = ["# Runtime controls", "",
           "Generated by `python tools/p4_controls.py --md docs/runtime_controls.md` from the current `port/` sources; do",
           "not edit by hand. A control is a file-scope `p4_*` variable with an initializer: the value is the default a",
           "build starts with. Diagnostic controls (checks, censuses, traces, probes, experiments) are listed apart.",
           "Poke one live with `tools/psp_probe_ab.py --set name=value` (PSPLink) or `P4_PRESS=\"27:addr=value\"` (PPSSPP).", ""]
    for title, diag in (("Runtime", False), ("Diagnostic", True)):
        rows = [c for c in items if c["diag"] == diag]
        out += [f"## {title} ({len(rows)})", "", "| Control | Default | Defined |", "|---|---:|---|"]
        out += [f"| `{c['name']}` | `{c['value']}` | [{c['file']}:{c['line']}](../port/{c['file']}#L{c['line']}) |" for c in rows]
        out.append("")
    return "\n".join(out)


def main():
    items = controls()
    names = [c["name"] for c in items]
    dupes = {n for n in names if names.count(n) > 1}
    assert not dupes, f"defined twice: {sorted(dupes)}"
    if len(sys.argv) > 2 and sys.argv[1] == "--md":
        Path(sys.argv[2]).write_text(markdown(items) + "\n", encoding="utf-8", newline="\n")
    diag = sum(c["diag"] for c in items)
    print(f"controls {len(items)}: runtime {len(items) - diag}, diagnostic {diag}")


if __name__ == "__main__":
    main()
